// Generate an RFC 9116 security.txt, and optionally clear-sign it with the gpg CLI.
import { spawnSync } from 'node:child_process';
import { lintSecurityTxt } from './securitytxt.js';

const list = (v) => [].concat(v ?? []).flatMap((x) => String(x).split(',')).map((x) => x.trim()).filter(Boolean);
/** "365d", "6m", "1y", or an ISO date -> ISO date-time (UTC, seconds precision). */
export function resolveExpires(v, now = new Date()) {
  const m = /^(\d+)\s*([dmy])$/i.exec(String(v ?? '365d').trim());
  let d;
  if (m) { d = new Date(now); const n = +m[1]; const u = m[2].toLowerCase(); if (u === 'd') d.setUTCDate(d.getUTCDate() + n); else if (u === 'm') d.setUTCMonth(d.getUTCMonth() + n); else d.setUTCFullYear(d.getUTCFullYear() + n); }
  else { d = new Date(v); if (Number.isNaN(+d)) throw new Error(`invalid expires: ${v}`); }
  return d.toISOString().replace(/\.\d{3}Z$/, 'Z');
}
const normContact = (c) => /^[a-z][a-z0-9+.-]*:/i.test(c) ? c : c.includes('@') ? `mailto:${c}` : /^\+?[\d\s-]+$/.test(c) ? `tel:${c.replace(/\s/g, '')}` : `https://${c}`;

/**
 * Build security.txt text. opts: contact (required, string|array), expires ("365d" | date), canonical, encryption,
 * acknowledgments, policy, hiring, csaf, preferredLanguages, comment, now.
 * Throws if the result would not pass the RFC 9116 required-field checks.
 */
export function generateSecurityTxt(opts = {}) {
  const contacts = list(opts.contact).map(normContact);
  if (!contacts.length) throw new Error('at least one Contact is required');
  const lines = [];
  if (opts.comment !== false) lines.push(`# ${opts.comment || 'Security contact information (RFC 9116). Generated by securitytxt-sentinel.'}`);
  for (const c of contacts) lines.push(`Contact: ${c}`);
  lines.push(`Expires: ${resolveExpires(opts.expires, opts.now ? new Date(opts.now) : new Date())}`);
  for (const [k, f] of [['encryption', 'Encryption'], ['acknowledgments', 'Acknowledgments'], ['policy', 'Policy'], ['hiring', 'Hiring'], ['csaf', 'CSAF'], ['canonical', 'Canonical']]) for (const v of list(opts[k])) lines.push(`${f}: ${v}`);
  if (opts.preferredLanguages) lines.push(`Preferred-Languages: ${list(opts.preferredLanguages).join(', ')}`);
  const text = lines.join('\n') + '\n';
  const errs = lintSecurityTxt(text, { now: opts.now, url: list(opts.canonical)[0] }).raw.filter((f) => !['unsigned', 'missing-canonical', 'expires-soon'].includes(f.rule));
  const fatal = errs.filter((f) => ['missing-contact', 'missing-expires', 'invalid-expires', 'expired', 'invalid-contact', 'insecure-uri', 'invalid-language'].includes(f.rule));
  if (fatal.length) throw new Error(fatal.map((f) => f.message).join('; '));
  return text;
}

/** Clear-sign with gpg (OpenPGP cleartext framework, as RFC 9116 section 2.3 asks). opts: { key, gpg = 'gpg', homedir, passphraseFile } */
export function signSecurityTxt(text, opts = {}) {
  const args = ['--batch', '--yes', '--armor', '--clearsign'];
  if (opts.homedir) args.unshift('--homedir', opts.homedir);
  if (opts.key) args.push('--local-user', opts.key);
  if (opts.passphraseFile) args.push('--pinentry-mode', 'loopback', '--passphrase-file', opts.passphraseFile);
  const r = spawnSync(opts.gpg || 'gpg', args, { input: text, encoding: 'utf8' });
  if (r.error) throw new Error(r.error.code === 'ENOENT' ? 'gpg is not installed (needed for --sign)' : r.error.message);
  if (r.status !== 0) throw new Error(`gpg failed: ${r.stderr.trim().split('\n').pop()}`);
  return r.stdout;
}
